// Версии правил движка. Сыгранные участки обязаны пересчитываться бит в бит (сохранения игроков,
// эталонные журналы), поэтому исправления механики включаются по номеру контрольной точки мира:
// всё, что было до КТ 2 (участки 1–2, слияния и сведение часов на КТ 1 и КТ 2), считается по-старому.
//
// Правила главы 2 (s.checkpoint >= 2):
// - «попить» и привычка «пить» берут сначала напитки, затем то, что лучше утоляет жажду;
// - кровотечение слабее 0,01/ч считается остановившимся — кровь восстанавливается;
// - кровь восстанавливается и при жажде (медленнее), так что из обморока от кровопотери выходят;
// - обработанные тяжёлые раны (тяжесть 4–5) со временем перестают кровоточить;
// - обморок (`faint`) длится ровно указанное время, если нет других причин;
// - пустой антисептик не работает, у аптечек считаются использования (`medical.uses`),
//   перевязку «кое-как» можно переделать как следует;
// - пустой пауэрбанк не заряжает (расход берётся из заряженного);
// - заживление не зависит от шага симуляции;
// - одежда намокает постепенно, дождевик защищает, мокрая одежда сохнет со временем.
import type { GameState } from './types';

export const CH2_CHECKPOINT = 2;

/** Действуют ли исправленные правила главы 2 для этого состояния мира. */
export const ch2Rules = (s: Pick<GameState, 'checkpoint'>): boolean => s.checkpoint >= CH2_CHECKPOINT;
