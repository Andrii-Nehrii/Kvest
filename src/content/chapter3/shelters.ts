function stores(n: number, stock: string): ActionDef[] {
  return [
    {
      ...task(
        n,
        'reserve',
        'Отложить из рюкзака пачку крупы',
        10,
        stock === 'c3_a_stock'
          ? 'Ты ставишь пачку к сухой стене, отдельно от рюкзака. На полу уже лежит доска. Бумажный край не намокнет снизу.'
          : stock === 'c3_b_stock'
            ? 'На полке освобождается место рядом с общей кастрюлей. Ты убираешь туда пачку, закрыв прищепкой открытый край. Рюкзак рядом больше не нужен.'
            : 'Ты кладёшь пачку на чистый верстак, подальше от масла. Между едой и инструментом ставишь пустую коробку. Крошкам теперь некуда сыпаться на железо.',
        [{ stock: 'oats', qty: 1, at: stock }],
      ),
      enabled: { has: 'oats' },
      disabledReason: 'В рюкзаке нет хлопьев',
    },
    {
      ...task(
        n,
        'draw_water',
        'Взять из общего запаса три литра',
        10,
        stock === 'c3_a_stock'
          ? 'Ты переливаешь воду над тазом. Крышки держишь сухими с внутренней стороны. Полные бутылки ставишь подальше от холодного окна.'
          : stock === 'c3_b_stock'
            ? 'На кухне хватает места только для двух бутылок. Ты наполняешь одну, закрываешь, потом берёшь вторую. Кружка остаётся рядом с общим запасом.'
            : 'Воду наливаешь подальше от железного поддона. Бутылки поднимаешь за горлышки, чтобы не зацепить масло с верстака. Крышки завинчиваются с первого раза.',
        [
          { unstock: 'water_l', qty: 3, at: stock },
          { take: 'water_l', qty: 3 },
          { give: 'water_15', qty: 2 },
        ],
      ),
      enabled: { stocked: 'water_l', qty: 3, at: stock },
      disabledReason: 'В общем запасе меньше трёх литров',
    },
  ];
}
