export function addRounds(scenes: Record<string, Scene>) {
  for (const [part, places] of Object.entries(rounds))
    for (const [place, entries] of Object.entries(places)) {
      const n = Number(part),
        home = scenes[`c${n}_${place}`];
      entries.forEach(([label, opening, inspect, finding, help, avoid], k) => {
        const id = `c${n}_round_${place}${k}`;
        home.actions.splice(home.actions.length - 1, 0, {
          id: `${id}_see`,
          label,
          minutes: 2,
          terminal: true,
          goto: `${id}_look`,
          when: all(not(flag(`$.${id}`)), { after: n < 7 ? 2 * 1440 + 6 * 60 : 3 * 1440 + 6 * 60 }),
        });
        scenes[`${id}_look`] = {
          id: `${id}_look`,
          for: 'any',
          chapter: 'ch3',
          location: home.location,
          title: label,
          calm: true,
          universal: false,
          text: [{ text: opening }],
          actions: [
            { id: `${id}_inspect`, label: inspect, minutes: 2, terminal: true, goto: `${id}_choice` },
          ],
        };
        scenes[`${id}_choice`] = {
          id: `${id}_choice`,
          for: 'any',
          chapter: 'ch3',
          location: home.location,
          title: label,
          calm: true,
          universal: false,
          text: [{ text: finding }],
          actions: [
            {
              id: `${id}_help`,
              label: help,
              minutes: 10,
              terminal: true,
              goto: home.id,
              text: results[n][place][k][0],
              effects: [
                { set: `$.${id}`, value: 'help' },
                { body: 'fatigue', delta: 3 },
              ],
            },
            {
              id: `${id}_avoid`,
              label: avoid,
              minutes: 6,
              terminal: true,
              goto: home.id,
              text: results[n][place][k][1],
              effects: [
                { set: `$.${id}`, value: 'avoid' },
                { body: 'stress', delta: 2 },
              ],
            },
          ],
        };
      });
    }
}
