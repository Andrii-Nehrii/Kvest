type ReadingSave = Pick<LocalSave, 'pairId' | 'replay' | 'me'> & { base?: { checkpoint: number } };

export function checkpointReadingFor(save: ReadingSave): readonly ReadingEntry[] {
  if (save.pairId !== REPLAY_PAIR || save.replay !== REPLAY_ID || !save.base) return [];
  const completed = save.base.checkpoint;
  return entries[save.me].filter(({ point }) => point <= completed);
}
