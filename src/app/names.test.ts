const split = (s: string) => (s.includes('|') ? s.split('|') : s.split(' '));

describe('падежи имени', () => {
  for (const [gender, table] of [['m', M], ['f', F]] as const) {
    it.each(table)(`${gender}: %s`, (name, expected) => {
      const f = guessForms(name, gender);
      expect(f.nom).toBe(name);
      expect([f.gen, f.dat, f.acc, f.ins, f.pre]).toEqual(split(expected));
    });
  }

  it('лишние пробелы убираются, в том числе вокруг дефиса', () => {
    expect(guessForms('  Анна   Иванова ', 'f')).toMatchObject({ nom: 'Анна Иванова', dat: 'Анне Ивановой' });
    expect(guessForms('Анна - Мария', 'f')).toMatchObject({ nom: 'Анна-Мария', ins: 'Анной-Марией' });
  });

  it('пустое имя, знаки и очень длинная строка не ломаются', () => {
    expect(guessForms('', 'm')).toEqual({ nom: '', gen: '', dat: '', acc: '', ins: '', pre: '' });
    expect(guessForms('   ', 'f').nom).toBe('');
    expect(guessForms('А.', 'm').gen).toBe('А.');
    expect(guessForms('Агент007', 'm').ins).toBe('Агент007');
    const long = 'Константин '.repeat(40).trim();
    const f = guessForms(long, 'm');
    expect(f.ins.split(' ')).toHaveLength(40);
    expect(guessForms('Я'.repeat(5000), 'f').gen).toHaveLength(5000);
  });

  it('ни одна форма не пустая', () => {
    for (const [gender, table] of [['m', M], ['f', F]] as const) {
      for (const [name] of table) {
        const f = guessForms(name, gender);
        for (const v of [f.gen, f.dat, f.acc, f.ins, f.pre]) expect(v.length).toBeGreaterThan(0);
      }
    }
  });
});
